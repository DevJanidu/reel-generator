import { chromium, expect } from "@playwright/test";
import { ensureBrowser } from "@remotion/renderer";
import { spawn } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
const root = process.cwd();
const store = path.join(
  root,
  "artifacts",
  "ui-smoke",
  new Date().toISOString().replaceAll(/[:.]/g, "-"),
);
await mkdir(store, { recursive: true });
const server = spawn(
  path.join(root, ".venv/Scripts/python.exe"),
  [
    "-m",
    "uvicorn",
    "services.api.main:app",
    "--host",
    "127.0.0.1",
    "--port",
    "8125",
  ],
  {
    cwd: root,
    env: {
      ...process.env,
      ODD_DATA_ROOT: store,
      ODD_PORT: "8125",
      ODD_AI_PROVIDER: "manual",
    },
    windowsHide: true,
    stdio: ["ignore", "pipe", "pipe"],
  },
);
let logs = "";
server.stdout.on("data", (d) => (logs += d));
server.stderr.on("data", (d) => (logs += d));
const browserInfo = await ensureBrowser();
let browser;
try {
  for (let i = 0; i < 80; i++) {
    try {
      const r = await fetch("http://127.0.0.1:8125/api/status");
      if (r.ok) break;
    } catch {}
    await new Promise((r) => setTimeout(r, 250));
  }
  browser = await chromium.launch({
    headless: true,
    executablePath: browserInfo.path,
  });
  const page = await browser.newPage({
    viewport: { width: 1440, height: 1100 },
  });
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  const controllerAccess = JSON.parse(
    await readFile(path.join(store, "data/controller-access.json"), "utf8"),
  ).token;
  await page.goto("http://127.0.0.1:8125/#controller=" + controllerAccess);
  await expect(
    page.getByRole("heading", { name: "Your next story starts here." }),
  ).toBeVisible();
  await expect(
    page.getByText("Official Content Bible", { exact: true }),
  ).toBeVisible();
  await expect(page.getByText("LOADED", { exact: true })).toHaveCount(4);
  await page.screenshot({
    path: path.join(store, "01-home-desktop.png"),
    fullPage: true,
  });
  await page
    .getByRole("button", { name: "Validate skills", exact: true })
    .click();
  await expect(
    page.getByText(
      "All four complete documents validated by byte length and SHA-256",
    ),
  ).toBeVisible();
  await page
    .getByRole("button", { name: "Create New Reel", exact: true })
    .click();
  await expect(
    page.getByRole("heading", { name: "Manual AI handoff" }),
  ).toBeVisible();
  await expect(page.getByRole("link", { name: "Full request" })).toBeVisible();
  const full = await fetch(
    "http://127.0.0.1:8125" +
      (await page
        .getByRole("link", { name: "Full request" })
        .getAttribute("href")),
  ).then((r) => r.json());
  expect(full.provenance.skills).toHaveLength(4);
  expect(full.request.messages[0].content.length).toBeGreaterThan(110000);
  await page.getByLabel("Working title").fill("Browser QA — Missing Key");
  await page.getByLabel("Genre", { exact: true }).fill("Mystery");
  await page
    .getByLabel("Your story premise")
    .fill(
      "Owner supplied QA premise about a missing key and a cautious rabbit.",
    );
  await page.getByRole("button", { name: "Use Custom Premise" }).click();
  await expect(
    page.getByRole("heading", { name: "The story, in your words" }),
  ).toBeVisible();
  await page
    .getByLabel("Story brief", { exact: true })
    .fill("Disposable browser QA story. Not generated by a live model.");
  await page
    .getByLabel("Full narration", { exact: true })
    .fill("The key was gone. The door was open. She stayed outside.");
  await page
    .getByRole("button", { name: "Save / Import Draft", exact: true })
    .click();
  await expect(
    page.getByRole("button", { name: "APPROVE SCRIPT & CONTINUE" }),
  ).toBeEnabled();
  await page.getByRole("button", { name: "APPROVE SCRIPT & CONTINUE" }).click();
  await expect(page.getByText(/Approved ·/)).toBeVisible();
  const pkg = JSON.parse(
    await new Promise((resolve, reject) => {
      const p = spawn(
        path.join(root, ".venv/Scripts/python.exe"),
        [
          "-c",
          "import json; from tests.fixtures import package; print(json.dumps(package()))",
        ],
        { cwd: root, windowsHide: true },
      );
      let out = "";
      p.stdout.on("data", (d) => (out += d));
      p.on("exit", (code) =>
        code ? reject(Error("fixture failed")) : resolve(out),
      );
    }),
  );
  await page.getByLabel("AI JSON response").fill(JSON.stringify(pkg));
  await page.getByRole("button", { name: "Validate & import JSON" }).click();
  await expect(page.getByText("SUCCEEDED", { exact: true })).toHaveCount(0); // state lives in picker; no false decorative success banner required
  await page
    .getByRole("button", { name: "Google Flow Prompts", exact: true })
    .click();
  await expect(
    page.getByRole("link", { name: "Download Flow JSON" }),
  ).toBeVisible();
  const link = await page
    .getByRole("link", { name: "Download Flow JSON" })
    .getAttribute("href");
  const flow = await fetch("http://127.0.0.1:8125" + link).then((r) =>
    r.json(),
  );
  expect(flow.jobs).toHaveLength(3);
  expect(flow.jobs.every((j) => j.type === "image")).toBe(true);
  await page
    .getByRole("button", { name: "Asset Manager", exact: true })
    .click();
  await page
    .getByRole("button", { name: "Refresh Assets", exact: true })
    .click();
  await expect(page.getByText(/S001: need exactly one/)).toBeVisible();
  await page
    .getByRole("button", { name: "Episode Workspace", exact: true })
    .click();
  await expect(
    page.getByText("Skill-loading evidence", { exact: true }),
  ).toBeVisible();
  await page.screenshot({
    path: path.join(store, "02-workspace-desktop.png"),
    fullPage: true,
  });
  const providerResults={};
  if(process.argv.includes('--providers')){
    await page.getByRole('button',{name:'Settings',exact:true}).click();
    await page.getByLabel('AI provider',{exact:true}).selectOption('codex_cli');
    await page.getByRole('button',{name:'Save settings',exact:true}).click();
    await expect(page.getByText('Save settings completed',{exact:true})).toBeVisible();
    for(const provider of ['codex_cli','claude_cli','manual','openai-compatible']){
      const response=page.waitForResponse(r=>r.url().endsWith('/api/providers/'+provider+'/test')&&r.request().method()==='POST',{timeout:350000});
      await page.getByRole('button',{name:'Test AI Connection · '+provider,exact:true}).click();
      const result=await (await response).json();providerResults[provider]=result;
      if(provider==='codex_cli')expect(result.success,JSON.stringify(result)).toBe(true);
      if(provider==='claude_cli')expect(['AUTHENTICATION','CONNECTED']).toContain(result.code);
      if(provider==='manual')expect(result.live_generation_tested).toBe(false);
      await expect(page.getByRole('button',{name:'Save settings',exact:true})).toBeEnabled();
    }
    await page.screenshot({path:path.join(store,'04-provider-settings.png'),fullPage:true});
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Home", exact: true }).click();
  await expect(
    page.getByRole("heading", { name: "Your next story starts here." }),
  ).toBeVisible();
  await page.screenshot({
    path: path.join(store, "03-home-mobile.png"),
    fullPage: true,
  });
  const overflow = await page.evaluate(
    () => document.documentElement.scrollWidth > window.innerWidth,
  );
  expect(overflow).toBe(false);
  expect(errors).toEqual([]);
  const report = {
    result: "PASS",
    store,
    executed: [
      "Desktop dashboard",
      "All four live skill statuses",
      "Functional Validate Skills",
      "Full manual model request download",
      "Custom premise selection",
      "Owner draft import",
      "Single approval via UI",
      "Manual preproduction JSON import",
      "Validated Flow download",
      "Missing-asset refresh feedback",
      "Workspace evidence/files",
      "390px mobile layout without horizontal overflow",
      "No browser runtime errors",
    ],
    screenshots: [
      "01-home-desktop.png",
      "02-workspace-desktop.png",
      "03-home-mobile.png",
    ],
    providerResults,
  };
  await writeFile(
    path.join(store, "RESULT.json"),
    JSON.stringify(report, null, 2),
  );
  await writeFile(
    path.join(root, "artifacts/ui-smoke/latest.json"),
    JSON.stringify(report, null, 2),
  );
  console.log(JSON.stringify(report, null, 2));
} catch (e) {
  await writeFile(path.join(store, "server.log"), logs);
  throw e;
} finally {
  if (browser) await browser.close();
  server.kill();
}
